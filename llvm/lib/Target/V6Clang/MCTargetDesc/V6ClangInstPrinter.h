#ifndef LLVM_LIB_TARGET_V6CLANG_MCTARGETDESC_V6ClangINSTPRINTER_H
#define LLVM_LIB_TARGET_V6CLANG_MCTARGETDESC_V6ClangINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class V6ClangInstPrinter : public MCInstPrinter {
public:
  V6ClangInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                 const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm8Operand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBrTarget(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printRegPair8080(const MCInst *MI, unsigned OpNo, raw_ostream &O);

  // Auto-generated by TableGen from V6ClangGenAsmWriter.inc.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst *MI) override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_V6CLANG_MCTARGETDESC_V6ClangINSTPRINTER_H
