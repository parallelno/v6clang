# sync_llvm_mirror.ps1
# Syncs all V6CLANG-related modifications from llvm-project/ (gitignored build source)
# into llvm/ (git-tracked mirror). Run after every successful build.
#
# V6CLANG target directory — full mirror (all files are ours)
# Upstream modified files — individual copies (only our changes to LLVM files)

$root = Split-Path $PSScriptRoot -Parent
if (-not $root) { $root = Split-Path (Get-Location) -Parent }

# V6CLANG backend target directory
robocopy "$root\llvm-project\llvm\lib\Target\V6CLANG" "$root\llvm\lib\Target\V6CLANG" /MIR /NFL /NDL /NJH /NJS

# V6CLANG lit tests — source of truth is llvm-project/, mirror to tests/lit/
# Use /MIR /XD Output to fully sync but skip Output/ dirs generated by lit
robocopy "$root\llvm-project\llvm\test\CodeGen\V6CLANG" "$root\tests\lit\CodeGen\V6CLANG" /MIR /XD Output /NFL /NDL /NJH /NJS
robocopy "$root\llvm-project\llvm\test\MC\V6CLANG" "$root\tests\lit\MC\V6CLANG" /MIR /XD Output /NFL /NDL /NJH /NJS
robocopy "$root\llvm-project\llvm\test\Linker\V6CLANG" "$root\tests\lit\Linker\V6CLANG" /MIR /XD Output /NFL /NDL /NJH /NJS
robocopy "$root\llvm-project\clang\test\CodeGen\V6CLANG" "$root\tests\lit\Clang\V6CLANG" /MIR /XD Output /NFL /NDL /NJH /NJS

# Modified upstream LLVM files
# M1: i8080 architecture registration in Triple
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\TargetParser\Triple.h" "$root\llvm\include\llvm\TargetParser\" > $null
xcopy /Y /I "$root\llvm-project\llvm\lib\TargetParser\Triple.cpp" "$root\llvm\lib\TargetParser\" > $null

# M9: Clang frontend integration
# TargetInfo (Basic/Targets)
xcopy /Y /I "$root\llvm-project\clang\lib\Basic\Targets\I8080.h" "$root\clang\lib\Basic\Targets\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Basic\Targets\I8080.cpp" "$root\clang\lib\Basic\Targets\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Basic\Targets.cpp" "$root\clang\lib\Basic\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Basic\CMakeLists.txt" "$root\clang\lib\Basic\" > $null
# TargetCodeGenInfo (CodeGen/Targets)
if (-not (Test-Path "$root\clang\lib\CodeGen\Targets")) { New-Item -ItemType Directory -Path "$root\clang\lib\CodeGen\Targets" -Force > $null }
xcopy /Y /I "$root\llvm-project\clang\lib\CodeGen\Targets\V6Clang.cpp" "$root\clang\lib\CodeGen\Targets\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\CodeGen\TargetInfo.h" "$root\clang\lib\CodeGen\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\CodeGen\CodeGenModule.cpp" "$root\clang\lib\CodeGen\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\CodeGen\CGCall.cpp" "$root\clang\lib\CodeGen\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\CodeGen\CMakeLists.txt" "$root\clang\lib\CodeGen\" > $null
# Driver ToolChain
if (-not (Test-Path "$root\clang\lib\Driver\ToolChains")) { New-Item -ItemType Directory -Path "$root\clang\lib\Driver\ToolChains" -Force > $null }
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\ToolChains\V6Clang.h" "$root\clang\lib\Driver\ToolChains\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\ToolChains\V6Clang.cpp" "$root\clang\lib\Driver\ToolChains\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\Driver.cpp" "$root\clang\lib\Driver\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\CMakeLists.txt" "$root\clang\lib\Driver\" > $null
# O70: V6CLANG driver options (-fno-v6clang-auto-include)
xcopy /Y /I "$root\llvm-project\clang\include\clang\Driver\Options.td" "$root\clang\include\clang\Driver\" > $null
# V6CLANG: clang attribute v6clang_rt_helper (lowers to LLVM string fn attr "v6clang-rt-helper").
xcopy /Y /I "$root\llvm-project\clang\include\clang\Basic\Attr.td" "$root\clang\include\clang\Basic\" > $null
# Clang.cpp (unsigned char default)
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\ToolChains\Clang.cpp" "$root\clang\lib\Driver\ToolChains\" > $null
# CommonArgs.cpp (frame pointer default)
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\ToolChains\CommonArgs.cpp" "$root\clang\lib\Driver\ToolChains\" > $null
# M9 step 5: Diagnostics
xcopy /Y /I "$root\llvm-project\clang\include\clang\Basic\DiagnosticSemaKinds.td" "$root\clang\include\clang\Basic\" > $null
xcopy /Y /I "$root\llvm-project\clang\lib\Sema\Sema.cpp" "$root\clang\lib\Sema\" > $null
# M9 step 6: Builtin intrinsics
xcopy /Y /I "$root\llvm-project\clang\include\clang\Basic\BuiltinsV6CLANG.def" "$root\clang\include\clang\Basic\" > $null
xcopy /Y /I "$root\llvm-project\clang\include\clang\Basic\TargetBuiltins.h" "$root\clang\include\clang\Basic\" > $null
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\IR\IntrinsicsV6CLANG.td" "$root\llvm\include\llvm\IR\" > $null
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\IR\Intrinsics.td" "$root\llvm\include\llvm\IR\" > $null
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\IR\CMakeLists.txt" "$root\llvm\include\llvm\IR\" > $null
# M9 step 6: Function.cpp (IntrinsicsV6CLANG.h include)
xcopy /Y /I "$root\llvm-project\llvm\lib\IR\Function.cpp" "$root\llvm\lib\IR\" > $null

# Loop-rotation opt-out hook in MachineBlockPlacement (gated by
# TargetSubtargetInfo::enableLoopRotationInBlockPlacement, overridden in V6CLANG).
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\CodeGen\TargetSubtargetInfo.h" "$root\llvm\include\llvm\CodeGen\" > $null
xcopy /Y /I "$root\llvm-project\llvm\lib\CodeGen\MachineBlockPlacement.cpp" "$root\llvm\lib\CodeGen\" > $null

# Debug metadata: relocatable global addresses in local DBG_VALUE locations.
if (-not (Test-Path "$root\llvm\lib\CodeGen\AsmPrinter")) { New-Item -ItemType Directory -Path "$root\llvm\lib\CodeGen\AsmPrinter" -Force > $null }
xcopy /Y /I "$root\llvm-project\llvm\lib\CodeGen\AsmPrinter\DebugLocEntry.h" "$root\llvm\lib\CodeGen\AsmPrinter\" > $null
xcopy /Y /I "$root\llvm-project\llvm\lib\CodeGen\AsmPrinter\DwarfDebug.cpp" "$root\llvm\lib\CodeGen\AsmPrinter\" > $null
xcopy /Y /I "$root\llvm-project\llvm\lib\CodeGen\AsmPrinter\DwarfCompileUnit.cpp" "$root\llvm\lib\CodeGen\AsmPrinter\" > $null
xcopy /Y /I "$root\llvm-project\llvm\lib\CodeGen\AsmPrinter\DwarfExpression.h" "$root\llvm\lib\CodeGen\AsmPrinter\" > $null
xcopy /Y /I "$root\llvm-project\llvm\lib\CodeGen\AsmPrinter\DwarfExpression.cpp" "$root\llvm\lib\CodeGen\AsmPrinter\" > $null

# O-LLD: ld.lld native linker integration
# EM_V6Clang machine ID added to ELF.h
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\BinaryFormat\ELF.h" "$root\llvm\include\llvm\BinaryFormat\" > $null
# V6CLANG relocation type names used by llvm-readelf and object tooling.
xcopy /Y /I "$root\llvm-project\llvm\lib\Object\ELF.cpp" "$root\llvm\lib\Object\" > $null
# V6CLANG ELF format/architecture recognition used by llvm-readobj/dwarfdump.
if (-not (Test-Path "$root\llvm\include\llvm\Object")) { New-Item -ItemType Directory -Path "$root\llvm\include\llvm\Object" -Force > $null }
xcopy /Y /I "$root\llvm-project\llvm\include\llvm\Object\ELFObjectFile.h" "$root\llvm\include\llvm\Object\" > $null
# V6CLANG lld backend (modeled on lld/ELF/Arch/MSP430.cpp)
if (-not (Test-Path "$root\lld\ELF\Arch")) { New-Item -ItemType Directory -Path "$root\lld\ELF\Arch" -Force > $null }
xcopy /Y /I "$root\llvm-project\lld\ELF\Arch\V6Clang.cpp" "$root\lld\ELF\Arch\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\Target.cpp" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\Target.h" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\Driver.cpp" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\Config.h" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\MapFile.cpp" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\Options.td" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\CMakeLists.txt" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\LinkerScript.cpp" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\InputSection.cpp" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\V6ClangPackedSections.cpp" "$root\lld\ELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\ELF\V6ClangPackedSections.h" "$root\lld\ELF\" > $null
# V6CLANG packed-section unit tests
if (-not (Test-Path "$root\lld\unittests\AsLibELF")) { New-Item -ItemType Directory -Path "$root\lld\unittests\AsLibELF" -Force > $null }
xcopy /Y /I "$root\llvm-project\lld\unittests\AsLibELF\CMakeLists.txt" "$root\lld\unittests\AsLibELF\" > $null
xcopy /Y /I "$root\llvm-project\lld\unittests\AsLibELF\V6ClangPackedSectionsTest.cpp" "$root\lld\unittests\AsLibELF\" > $null
# V6CLANG default linker script (data resource for the driver)
if (-not (Test-Path "$root\clang\lib\Driver\ToolChains\V6CLANG")) { New-Item -ItemType Directory -Path "$root\clang\lib\Driver\ToolChains\V6CLANG" -Force > $null }
xcopy /Y /I "$root\llvm-project\clang\lib\Driver\ToolChains\V6CLANG\v6clang.ld" "$root\clang\lib\Driver\ToolChains\V6CLANG\" > $null
# V6CLANG resource-dir headers (string.h, stdlib.h, v6clang.h)
$resourceInclude = "$root\llvm-project\clang\lib\Driver\ToolChains\V6CLANG\include"
if (Test-Path $resourceInclude) {
	robocopy $resourceInclude "$root\clang\lib\Driver\ToolChains\V6CLANG\include" /MIR /NFL /NDL /NJH /NJS > $null
	if ($LASTEXITCODE -gt 7) { throw "Failed to mirror V6CLANG resource headers (robocopy exit $LASTEXITCODE)" }
}

Write-Host "Mirror sync complete."
$global:LASTEXITCODE = 0
